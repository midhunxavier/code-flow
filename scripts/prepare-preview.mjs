// Build and pack once, then derive Homebrew metadata and checksums from that exact tarball.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const pkg = JSON.parse(await readFile(join(root, "package.json"), "utf8"));
if (!/^\d+\.\d+\.\d+-preview\.\d+$/.test(pkg.version)) throw new Error("Choose an explicit x.y.z-preview.N version before preparing a preview.");
execFileSync(process.execPath, ["scripts/package-npm.mjs"], { cwd: root, stdio: "inherit" });
const output = join(root, "output/releases");
await mkdir(output, { recursive: true });
const npm = process.platform === "win32" ? "npm.cmd" : "npm";
const packed = JSON.parse(execFileSync(npm, ["pack", "./dist/npm", "--json", "--ignore-scripts", "--pack-destination", output], { cwd: root, encoding: "utf8" }))[0];
const sha = createHash("sha256").update(await readFile(join(output, packed.filename))).digest("hex");
await writeFile(join(output, `${packed.filename}.sha256`), `${sha}  ${packed.filename}\n`);
const url = `https://github.com/midhunxavier/code-flow/releases/download/v${pkg.version}/${packed.filename}`;
await mkdir(join(output, "Formula"), { recursive: true });
await writeFile(join(output, "Formula/code-flow.rb"), `# Generated by npm run release:prepare from the exact preview tarball.
class CodeFlow < Formula
  desc "Run your coding agents together in a local browser workspace"
  homepage "https://midhunxavier.github.io/code-flow/"
  url "${url}"
  version "${pkg.version}"
  sha256 "${sha}"
  license "MIT"

  depends_on "node@22"
  depends_on "git"

  def install
    libexec.install Dir["*"]
    (bin/"codeflow").write <<~SH
      #!/bin/sh
      exec "#{Formula["node@22"].opt_bin}/node" "#{libexec}/bin/codeflow.mjs" "$@"
    SH
    (bin/"codeflow").chmod 0755
    bin.install_symlink bin/"codeflow" => "code-flow"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/codeflow --version")
  end
end
`);
await writeFile(join(output, "preview-notes.md"), `# Code Flow ${pkg.version}\n\nRun your installed coding agents in one local workspace. This is an early preview.\n\n## Try the exact release\n\nWith Node.js 22.13+ and Git 2.38+ installed:\n\n\`\`\`sh\nnpx --yes --package=${url} codeflow\n\`\`\`\n\nThe app opens in your browser. Keep the terminal open and press Ctrl+C to stop. Install and sign in to at least one supported agent CLI before starting a run.\n\n## Installation channels\n\n- npm: after registry publication, use \`npx @midhunxavier/code-flow@preview\` or \`npm install -g @midhunxavier/code-flow@preview\`.\n- macOS: choose the arm64 DMG for Apple Silicon or x64 for Intel. Drag Code Flow to Applications. Node is bundled; use the menu bar to reopen or quit. Files marked \`unnotarized\` are developer builds and macOS may block them.\n- Linux: use the npm launcher.\n- Windows: use WSL2; native Windows execution is not supported in this preview.\n- Homebrew: the attached \`code-flow.rb\` is generated from the tarball checksum. Copy it to \`Formula/code-flow.rb\` in the maintainer's Homebrew tap before advertising \`brew install midhunxavier/code-flow/code-flow\`.\n\nSettings and history live in \`~/.codeflow\` and survive reinstalling. Read the [installation guide](https://midhunxavier.github.io/code-flow/installation.html).\n`);
console.log(`Prepared ${packed.filename}, SHA-256, Homebrew formula and preview notes in output/releases.`);
