import { test } from "node:test";
import assert from "node:assert/strict";
import { request } from "node:http";
import { spawn, type ChildProcess } from "node:child_process";
import { mkdir } from "node:fs/promises";
import { chromium, type Page, type Browser } from "playwright-core";
import { buildHost, fixture, pause, port, root } from "../ssh-project-fixture.js";

test("connect from the app, browse a remote folder, run there, reconnect and return to local work", { timeout: 180_000 }, async () => {
  buildHost(); const f = await fixture(); let server: ChildProcess | undefined, browser: Browser | undefined, page: Page | undefined;
  const localPort = await port(), base = `http://localhost:${localPort}`, token = "ssh-e2e-owner";
  try {
    server = spawn(process.execPath, ["--import", "tsx", "src/server.ts"], { cwd: root, env: { ...process.env, PORT: String(localPort), CODEFLOW_HOME: f.localHome, CODEFLOW_TOKEN: token, PATH: `${f.bin}:${process.env.PATH}` }, stdio: "ignore" });
    for (let i = 0; i < 150; i++) { if (await fetch(base + "/api/health", { headers: { authorization: `Bearer ${token}` } }).then((res) => res.ok, () => false)) break; await pause(200); }
    browser = await chromium.launch({ channel: "chrome", headless: true });
    page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    await page.goto(`${base}/?token=${token}`);
    const localProject = await page.evaluate(async () => (await fetch("/api/projects", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ name: "Remote web app", repos: [] }) })).json());
    const secondLocalProject = await page.evaluate(async () => (await fetch("/api/projects", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ name: "Another local project", repos: [] }) })).json());
    await page.getByRole("button", { name: "Application menu", exact: true }).click();
    await page.getByRole("menuitem", { name: /^Settings/ }).click();
    await page.getByRole("link", { name: "Connections", exact: true }).click();
    const dialog = page.locator(".settings-content");
    await dialog.getByLabel("SSH host", { exact: true }).fill("fixture");
    await dialog.getByLabel("Display name").fill("Linux development");
    await dialog.getByLabel("SSH port", { exact: true }).fill("2222");
    await dialog.getByLabel("Identity file", { exact: true }).fill("~/.ssh/development");
    await dialog.getByRole("button", { name: "Save connection", exact: true }).click();
    await dialog.getByRole("button", { name: "Open Linux development" }).waitFor();
    // New project selects the machine before browsing, carrying only its name across.
    await page.getByRole("button", { name: "New project", exact: true }).click();
    const projectDialog = page.getByRole("dialog", { name: "New project", exact: true });
    await projectDialog.getByLabel("Name", { exact: true }).fill("Remote web app");
    await projectDialog.getByRole("button", { name: "Project computer", exact: true }).click();
    await projectDialog.getByRole("menuitem", { name: /^Linux development/ }).click();
    await page.getByRole("button", { name: "SSH connections", exact: true }).filter({ hasText: "Linux development" }).waitFor({ timeout: 90_000 });
    assert.equal(new URL(page.url()).origin, base);
    await projectDialog.waitFor();
    assert.equal(await projectDialog.getByLabel("Name", { exact: true }).inputValue(), "Remote web app");
    assert.equal(await projectDialog.locator(".project-repos .dir").count(), 0);
    await projectDialog.getByRole("button", { name: "Add repository…", exact: true }).click();
    const picker = page.getByRole("dialog", { name: "Add a repository to Remote web app", exact: true });
    await picker.getByRole("button", { name: "Open folder project", exact: true }).waitFor();
    assert.equal(await picker.getByLabel("Folder path").inputValue(), f.remoteHome);
    await picker.locator(".dir", { has: page.getByRole("button", { name: "Open folder project", exact: true }) }).getByRole("button", { name: "Use", exact: true }).click();
    await picker.waitFor({ state: "hidden" });
    await projectDialog.getByRole("button", { name: "Remove project", exact: true }).waitFor();
    await projectDialog.getByRole("button", { name: "Create project", exact: true }).click();
    await projectDialog.waitFor({ state: "hidden" });
    await page.locator(".page-head-actions").getByRole("button", { name: "New run", exact: true }).click();
    await page.locator(".repo-btn:not(.project-btn) .name", { hasText: "project" }).waitFor();
    await openAdvanced(page);
  await page.getByLabel("Workflow", { exact: true }).selectOption("pipeline");
    await page.getByLabel("Task", { exact: true }).fill("SSH E2E: work on the server");
    await page.getByRole("button", { name: /^Start run/ }).click();
    await page.locator(".runview .run-head h2", { hasText: "SSH E2E: work on the server" }).waitFor();
    const runId = page.url().split("/run/")[1]!;
    const remotePath = new URL(page.url()).pathname;
    const computerId = remotePath.split("/")[2]!;
    assert.match(remotePath, /^\/computer\/[a-f0-9]{16}\/$/);
    // Reload restores a dropped connection without opening a new browser origin.
    await page.evaluate(async (id) => fetch(`/api/ssh-hosts/${id}/disconnect`, { method: "POST", headers: { "content-type": "application/json" }, body: "{}" }), computerId);
    await page.reload();
    await page.locator(".runview .run-head h2", { hasText: "SSH E2E: work on the server" }).waitFor({ timeout: 60_000 });
    assert.equal(new URL(page.url()).pathname, remotePath);
    const run = await page.evaluate(async (id) => (await fetch(`${location.pathname}api/runs/${id}`)).json(), runId);
    assert.ok(run.repo.endsWith("/remote/project"));
    await page.getByRole("button", { name: "SSH connections", exact: true }).click();
    await page.getByRole("menuitem", { name: /^This computer/ }).click();
    await page.waitForURL(url => url.pathname === "/");
    await page.getByRole("button", { name: "SSH connections", exact: true }).filter({ hasText: "This computer" }).waitFor();
    assert.equal(new URL(page.url()).origin, base);
    assert.deepEqual((await page.evaluate(async () => (await fetch("/api/projects")).json())).map((p: any) => p.id).sort(), [localProject.id, secondLocalProject.id].sort(), "remote projects never enter local project storage");
    await page.getByRole("button", { name: "SSH connections", exact: true }).click();
    await page.getByRole("menuitem", { name: /^Linux development/ }).waitFor();
    assert.equal(await page.getByLabel("SSH host", { exact: true }).count(), 0, "the quick switcher has no setup form");
    await page.getByRole("menuitem", { name: /^Linux development/ }).click();
    await page.waitForURL(url => url.pathname === remotePath);
    await page.getByRole("button", { name: "SSH connections", exact: true }).filter({ hasText: "Linux development" }).waitFor();
    assert.equal(page.context().pages().length, 1, "switching stays in the same tab");
    const restoredProjects = await page.evaluate(async () => { const response = await fetch(`${location.pathname}api/projects`); return { status: response.status, body: await response.json() }; });
    assert.equal(restoredProjects.status, 200, JSON.stringify(restoredProjects.body));
    assert.deepEqual(restoredProjects.body.map((project: { name: string }) => project.name), ["Remote web app"]);
    await page.setViewportSize({ width: 1440, height: 1000 });
    const localGroup = page.getByRole("group", { name: "This computer projects", exact: true });
    await localGroup.getByRole("link", { name: "Remote web app", exact: true }).waitFor();
    const directory = await page.evaluate(async () => (await fetch("/api/workspace-projects")).json());
    assert.equal(directory.computers.length, 2);
    const sidebarOrder = () => page!.locator(".computer-projects").evaluateAll((groups) => groups.map((group) => ({ computer: group.getAttribute("data-computer-id"), projects: [...group.querySelectorAll(".proj-head .pn, .connected-project-link > span")].map((name) => name.textContent) })));
    const expectedOrder = [{ computer: "local", projects: ["Another local project", "Remote web app"] }, { computer: computerId, projects: ["Remote web app"] }];
    await page.locator(`.computer-projects[data-computer-id="${computerId}"] .proj-head .pn`).filter({ hasText: "Remote web app" }).waitFor();
    assert.deepEqual(await sidebarOrder(), expectedOrder, "the remote workspace keeps local projects first");
    assert.ok(directory.computers.every((host: any) => host.projects.every((p: any) => Object.keys(p).sort().join() === "id,name")), "only project names and IDs cross workspace boundaries");
    await localGroup.getByRole("link", { name: "Remote web app", exact: true }).click();
    await page.getByRole("heading", { name: "Remote web app", exact: true }).waitFor();
    assert.equal(new URL(page.url()).origin, base);
    assert.ok(page.url().endsWith(`/project/${localProject.id}`));
    const remoteGroup = page.getByRole("group", { name: "Linux development projects", exact: true });
    const remoteLink = remoteGroup.getByRole("link", { name: "Remote web app", exact: true });
    await remoteLink.waitFor();
    assert.deepEqual(await sidebarOrder(), expectedOrder, "opening a local project preserves computer and project order");
    const destination = await remoteLink.getAttribute("href");
    assert.equal(new URL(destination!, base).origin, base);
    const remoteApi = `${base}${remotePath}api/fs`;
    assert.equal((await fetch(remoteApi)).status, 403, "remote operations require the local owner session");
    assert.equal((await fetch(remoteApi, { headers: { authorization: `Bearer ${token}`, origin: "https://evil.example" } })).status, 403);
    assert.equal(await new Promise<number>((resolve, reject) => { request(remoteApi, { headers: { authorization: `Bearer ${token}`, host: "evil.example" } }, (res) => { res.resume(); resolve(res.statusCode!); }).on("error", reject).end(); }), 403);
    const remoteResponse = await fetch(remoteApi, { headers: { authorization: `Bearer ${token}` } });
    assert.equal((await remoteResponse.json()).home, f.remoteHome);
    assert.match(remoteResponse.headers.get("content-security-policy")!, /^sandbox allow-downloads;/);
    assert.equal((await fetch(`${base}/computer/0000000000000000/api/projects`, { headers: { authorization: `Bearer ${token}` } })).status, 404);
    assert.equal((await fetch(`${base}${remotePath}api/projects/${localProject.id}`, { headers: { authorization: `Bearer ${token}` } })).status, 404, "a remote project request never falls back to the local project");
    assert.equal((await fetch(`${base}${remotePath}`, { headers: { authorization: `Bearer ${token}` } }).then((r) => r.text())).includes(`window.__CODEFLOW_WORKSPACE="${computerId}"`), true);
    await mkdir("output/playwright", { recursive: true });
    await page.screenshot({ path: "output/playwright/connected-projects-desktop.png", animations: "disabled" });
    await remoteLink.click();
    await page.getByRole("heading", { name: "Remote web app", exact: true }).waitFor();
    assert.equal(new URL(page.url()).origin, base);
    assert.ok(!page.url().endsWith(`/project/${localProject.id}`));
    assert.equal(page.context().pages().length, 1);
    await localGroup.getByRole("link", { name: "Another local project", exact: true }).waitFor();
    assert.deepEqual(await sidebarOrder(), expectedOrder, "opening the remote project again preserves the same order");
    const remoteProjectUrl = page.url();
    await page.goBack();
    await page.getByRole("heading", { name: "Remote web app", exact: true }).waitFor();
    assert.ok(page.url().endsWith(`/project/${localProject.id}`));
    await page.goForward();
    await page.getByRole("heading", { name: "Remote web app", exact: true }).waitFor();
    assert.equal(page.url(), remoteProjectUrl);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole("button", { name: "Show runs", exact: true }).click();
    await localGroup.getByRole("link", { name: "Remote web app", exact: true }).waitFor();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: "output/playwright/connected-projects-mobile.png", animations: "disabled" });
    await localGroup.getByRole("link", { name: "Remote web app", exact: true }).click();
    await page.getByRole("heading", { name: "Remote web app", exact: true }).waitFor();
    const remoteHost = directory.computers.find((host: any) => host.id !== "local");
    await page.evaluate(async (id) => fetch(`/api/ssh-hosts/${id}/disconnect`, { method: "POST", headers: { "content-type": "application/json" }, body: "{}" }), remoteHost.id);
    const remaining = await page.evaluate(async () => (await fetch("/api/workspace-projects")).json());
    assert.deepEqual(remaining.computers.map((host: any) => host.id), ["local"], "disconnected computers are not queried or reconnected");

  } catch (error) {
    console.error("SSH browser failure:", (error as Error).message, await page?.locator("body").innerText().catch(() => "page unavailable"));
    await mkdir("output/playwright", { recursive: true }); await page?.screenshot({ path: "output/playwright/ssh-project-failure.png", fullPage: true }).catch(() => undefined);
    throw error;
  } finally {
    await browser?.close();
    if (server && server.exitCode === null) { server.kill("SIGTERM"); await new Promise<void>((resolve) => { const timer = setTimeout(() => { server!.kill("SIGKILL"); resolve(); }, 10000); server!.once("exit", () => { clearTimeout(timer); resolve(); }); }); }
    await f.cleanup();
  }
});

async function openAdvanced(page: Page) {
  const options = page.locator(".composer-options");
  if (await options.getAttribute("open") === null) await options.locator(":scope > summary").click();
  const advanced = page.locator(".advanced-controls");
  if (await advanced.getAttribute("open") === null) await advanced.locator(":scope > summary").click();
}
