const root = fileURLToPath(new URL("../..", import.meta.url));
const live = process.env.CODEFLOW_TEST_LIVE_AGENTS === "1";
const port = await new Promise<number>(resolve => { const server = createServer().listen(0, "127.0.0.1", () => { const p = (server.address() as {port:number}).port; server.close(() => resolve(p)); }); });
const base = `http://127.0.0.1:${port}`, token = "agent-mode-e2e";
const home = mkdtempSync(join(tmpdir(), "cf-agent-ui-")), repo = join(home, "repo");
let server: ChildProcess, browser: Browser, page: Page;
const headers = { authorization: `Bearer ${token}`, "content-type": "application/json" };
async function api(path: string, body?: unknown) { const response = await fetch(`${base}${path}`, { method: body === undefined ? "GET" : "POST", headers, ...(body === undefined ? {} : { body: JSON.stringify(body) }) }); const value = await response.json() as any; assert.ok(response.ok, JSON.stringify(value)); return value; }
async function done(id: string) { const deadline = Date.now() + (live ? 300000 : 30000); while (Date.now() < deadline) { const run = await api(`/api/runs/${id}`); if (run.status !== "running") { assert.equal(run.status, "done", run.error); return run; } await new Promise(resolve => setTimeout(resolve, 200)); } throw new Error("Agent chat did not finish"); }
before(async () => {
  if (live) console.log("Live UI: starting isolated server");
  mkdirSync(repo); const git = (...args: string[]) => execFileSync("git", args, { cwd: repo });
  git("init", "-q", "-b", "main"); writeFileSync(join(repo, "README.md"), "Agent chat UI fixture\n"); git("add", "."); git("-c", "user.name=Test", "-c", "user.email=t@t", "commit", "-qm", "Fixture");
  execFileSync(process.execPath, ["scripts/build-ui.mjs"], { cwd: root });
  server = spawn(process.execPath, ["--import", "tsx", "src/server.ts"], { cwd: root, env: { ...process.env, PORT: String(port), CODEFLOW_HOME: join(home, "state"), CODEFLOW_TOKEN: token, ...(live ? {} : { PATH: `${root}/test/fake-bin:${process.env.PATH}`, FAKE_SLEEP_MS: "2000" }) }, stdio: "ignore" });
  for (let n=0; n<150; n++) { if (await fetch(`${base}/api/health`, {headers}).then(r=>r.ok,()=>false)) break; await new Promise(resolve=>setTimeout(resolve,200)); }
  if (live) console.log("Live UI: launching browser");
  browser = await chromium.launch({ channel: "chrome", headless: true }); page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  if (live) console.log("Live UI: browser ready");
  page.setDefaultTimeout(live ? 90000 : 15000);
  await page.addInitScript(({ repository }) => { localStorage.setItem("repo", repository); localStorage.setItem("pattern", "solo"); if (localStorage.getItem("sideOpen") === null) localStorage.setItem("sideOpen", "0"); }, {repository:repo});
});
after(async () => { await browser?.close(); server?.kill("SIGTERM"); });

