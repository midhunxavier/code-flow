test("closing the final working tab keeps its agent running and the task can be reopened", {skip: live, timeout: 30000}, async () => {
  const all = await api("/api/runs");
  const separate = all.find((run:any) => run.task.startsWith("A separate task"));
  await page.goto(`${base}/#/run/${separate.id}`);
  const main = page.locator(".runview");
  await main.getByRole("textbox", {name:"Message agent",exact:true}).fill("Keep working after the tab closes");
  await main.getByRole("button", {name:"Send",exact:true}).click();
  await main.getByRole("group", {name:"Agent chats",exact:true}).getByRole("img", {name:"working",exact:true}).waitFor();
  await main.getByRole("button", {name:/^Close Codex/}).click();
  await page.getByText("Tab closed. The agent continues working; reopen it from this task.", {exact:true}).waitFor();
  const result = await done(separate.id);
  assert.equal(result.followUps.at(-1).message, "Keep working after the tab closes");
  assert.equal(result.archived, false);
  await page.getByRole("navigation", {name:"Runs",exact:true}).locator(".run-item").filter({hasText:"A separate task"}).click();
  await page.waitForURL(new RegExp(separate.id));
  await main.getByText("Keep working after the tab closes", {exact:true}).waitFor();
});

test("sidebar task actions archive, restore and delete the whole chat family", {skip: live, timeout: 60000}, async () => {
  const all = await api("/api/runs");
  const rootRun = all.find((run:any) => run.task === "Agent UI first message");
  const family = await api(`/api/runs/${rootRun.id}/chats`);
  assert.equal(family.length, 3);
  const rail = page.getByRole("navigation", {name:"Runs",exact:true});
  const row = rail.getByRole("group", {name:"Agent UI first message",exact:true});
  await row.getByRole("button", {name:"Run actions",exact:true}).click();
  await page.getByRole("menuitem", {name:"Archive",exact:true}).click();
  await row.waitFor({state:"detached"});
  for (const chat of family) assert.equal((await api(`/api/runs/${chat.id}`)).archived, true);
  await rail.getByRole("button", {name:"Show archived runs",exact:true}).click();
  await row.getByRole("button", {name:"Run actions",exact:true}).click();
  await page.getByRole("menuitem", {name:"Unarchive",exact:true}).click();
  // Wait for the action on every member before exercising deletion.
  await rail.getByRole("button", {name:"Hide archived runs",exact:true}).click();
  await row.waitFor();
  for (let n=0;n<100;n++) {
    const current = await api(`/api/runs/${rootRun.id}/chats`);
    if (current.every((run:any) => !run.archived)) break;
    await new Promise(resolve => setTimeout(resolve,50));
  }
  for (const chat of family) assert.equal((await api(`/api/runs/${chat.id}`)).archived, false);
  await row.getByRole("button", {name:"Run actions",exact:true}).click();
  await page.getByRole("menuitem", {name:"Delete…",exact:true}).click();
  const dialog = page.getByRole("dialog", {name:"Delete 3 runs?",exact:true});
  await dialog.getByRole("button", {name:"Delete 3 runs",exact:true}).click();
  await dialog.waitFor({state:"detached"});
  assert.equal(await rail.locator(".run-item").count(),1);
  const remaining = await api("/api/runs");
  assert.equal(remaining.length,1);
  assert.ok(remaining[0].task.startsWith("A separate task"));
});
