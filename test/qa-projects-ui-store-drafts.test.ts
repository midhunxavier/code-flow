import test from 'node:test';
import assert from 'node:assert/strict';
const values = new Map<string, string>([['projectDraftVersion', '1'], ['composerProject', 'broken'], ['project-draft-v1:broken', '{corrupt'], ['project-draft-v1:future', '{"version":2,"task":"Future data"}']]);
Object.assign(globalThis, { window: { innerWidth: 1440, addEventListener() { } }, document: { addEventListener() { }, hidden: false }, location: { hostname: 'localhost', hash: '', origin: 'http://localhost', search: '' }, localStorage: { getItem: (k: string) => values.get(k) ?? null, setItem: (k: string, v: string) => values.set(k, v), removeItem: (k: string) => values.delete(k) } });
globalThis.fetch = (async (input: string) => { const u = new URL(input, 'http://localhost'), repo = u.searchParams.get('repo'); return new Response(JSON.stringify(u.pathname === '/api/branches' ? { repo, current: 'main', branches: [{ name: 'main' }], worktreeRoot: `${repo}/worktrees` } : {})); }) as typeof fetch;
const s = await import('../ui/state.js');
test('a corrupt startup key stays untouched while other projects and overview drafts work', async () => {
    s.projects.value = [{ id: 'a', name: 'A', repos: ['/a'], createdAt: 1 }, { id: 'b', name: 'B', repos: ['/b'], createdAt: 1 }, { id: 'broken', name: 'Broken', repos: [], createdAt: 1 }];
    s.projectsLoaded.value = true;
    await s.initializeProjectDrafts();
    assert.equal(s.draftsReady.value, true);
    assert.match(s.draftUnavailable.value, /retained/);
    await s.saveComposerDraft();
    assert.equal(values.get('project-draft-v1:broken'), '{corrupt');
    assert.equal(await s.openComposer('a'), true);
    s.setTask('Draft A');
    await s.saveComposerDraft();
    assert.equal(await s.openComposer('b'), true);
    s.setTask('Draft B');
    await s.saveComposerDraft();
    assert.equal(await s.savedDraftTask('a'), 'Draft A');
    assert.equal(s.task.value, 'Draft B');
    assert.equal(await s.openComposer('a'), true);
    assert.equal(s.task.value, 'Draft A');
    assert.equal(await s.savedDraftTask('b'), 'Draft B');
    assert.equal(values.get('project-draft-v1:broken'), '{corrupt');
});
test('opening an unsupported key leaves a stable recovery message and the healthy draft usable', async () => {
    assert.equal(await s.openComposer('future'), false);
    await s.saveComposerDraft();
    assert.match(s.unreadableDrafts.value.future!, /unsupported/);
    assert.equal(values.get('project-draft-v1:future'), '{"version":2,"task":"Future data"}');
    assert.equal(s.composerLoading.value, false);
    assert.deepEqual(s.route.value, { view: 'composer', project: 'a' });
    assert.equal(s.task.value, 'Draft A');
    assert.equal(await s.openComposer('b'), true);
    assert.equal(s.task.value, 'Draft B');
});
test('missing empty-repository drafts expose destination recovery and carry into an empty project draft', async () => {
    await s.openComposer('missing');
    s.setTask('Retained missing-project draft');
    assert.equal(s.repo.value, '');
    assert.equal(s.target.value.unavailable, true);
    assert.match(s.target.value.problem, /unavailable/);
    s.projects.value = [...s.projects.value, { id: 'new', name: 'New', repos: ['/new'], createdAt: 1 }];
    assert.equal(await s.openComposer('new', { carryUnassigned: true }), true);
    assert.equal(s.task.value, 'Retained missing-project draft');
    assert.equal(await s.savedDraftTask('missing'), 'Retained missing-project draft');
});
